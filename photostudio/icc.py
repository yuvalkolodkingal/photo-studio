"""Generated ICC v2 matrix/TRC profiles for the export colour spaces (sRGB, Display P3, Adobe RGB 1998,
Rec.2020 with the sRGB curve is intentionally absent: exports use one of the three below).

No binary profiles are shipped; they are built on demand from the primaries in ``photostudio.color`` and
Bradford-adapted to the D50 PCS, exactly like the reference profiles. ``profile_bytes(name)`` returns the bytes
to embed (Pillow ``icc_profile=``, TIFF tag 34675, PNG ``iCCP``)."""
from __future__ import annotations

import struct
import zlib
from functools import lru_cache

import numpy as np

from . import color

# name -> (RGB->XYZ(D65) matrix, trc spec, description)
_SPACES = {
    "srgb": (color.SRGB_TO_XYZ, "srgb", "sRGB IEC61966-2.1 (photostudio)"),
    "p3": (color.P3_TO_XYZ, "srgb", "Display P3 (photostudio)"),
    "adobe": (np.array([[0.5767309, 0.1855540, 0.1881852],
                        [0.2973769, 0.6273491, 0.0752741],
                        [0.0270343, 0.0706872, 0.9911085]]), 2.19921875, "Adobe RGB (1998) (photostudio)"),
}
ALIASES = {"srgb": "srgb", "s": "srgb", "p3": "p3", "displayp3": "p3", "display_p3": "p3", "display-p3": "p3",
           "adobe": "adobe", "adobergb": "adobe", "adobe_rgb": "adobe", "adobe-rgb": "adobe", "argb": "adobe"}
D50_XYZ = (0.9642, 1.0, 0.8249)


def canonical(name: str) -> str:
    key = str(name).strip().lower().replace(" ", "")
    if key not in ALIASES:
        raise ValueError(f"unknown colour space '{name}' (srgb | p3 | adobe)")
    return ALIASES[key]


def _s15f16(v: float) -> bytes:
    return struct.pack(">i", int(round(v * 65536.0)))


def _xyz_tag(x: float, y: float, z: float) -> bytes:
    return b"XYZ \x00\x00\x00\x00" + _s15f16(x) + _s15f16(y) + _s15f16(z)


def _curv_gamma(g: float) -> bytes:
    return b"curv\x00\x00\x00\x00" + struct.pack(">I", 1) + struct.pack(">H", int(round(g * 256.0))) + b"\x00\x00"


def _curv_table(values: np.ndarray) -> bytes:
    v = np.clip(np.rint(values * 65535.0), 0, 65535).astype(">u2")
    return b"curv\x00\x00\x00\x00" + struct.pack(">I", len(v)) + v.tobytes()


def _text_desc(text: str) -> bytes:
    ascii_ = text.encode("ascii", "replace") + b"\x00"
    return (b"desc\x00\x00\x00\x00" + struct.pack(">I", len(ascii_)) + ascii_ + struct.pack(">II", 0, 0)
            + struct.pack(">HB", 0, 0) + b"\x00" * 67)


def _text(text: str) -> bytes:
    return b"text\x00\x00\x00\x00" + text.encode("ascii", "replace") + b"\x00"


def _pad4(b: bytes) -> bytes:
    return b + b"\x00" * (-len(b) % 4)


def build_profile(name: str) -> bytes:
    """Build the ICC v2.4 display profile for ``name`` (srgb | p3 | adobe)."""
    key = canonical(name)
    m_rgb2xyz, trc, desc = _SPACES[key]
    cat = color.cat_matrix(color.D65_XY, color.D50_XY, "bradford")
    col = cat @ np.asarray(m_rgb2xyz, np.float64)       # columns = R,G,B primaries in D50 PCS
    if trc == "srgb":
        xs = np.linspace(0.0, 1.0, 1024)
        curve = _curv_table(color.srgb_eotf(xs.astype(np.float32)).astype(np.float64))
    else:
        curve = _curv_gamma(float(trc))
    tags = {
        b"desc": _text_desc(desc),
        b"cprt": _text("Generated by photostudio; no copyright, free to use."),
        b"wtpt": _xyz_tag(*D50_XYZ),
        b"rXYZ": _xyz_tag(*col[:, 0]),
        b"gXYZ": _xyz_tag(*col[:, 1]),
        b"bXYZ": _xyz_tag(*col[:, 2]),
        b"rTRC": curve, b"gTRC": curve, b"bTRC": curve,
    }
    n = len(tags)
    table_size = 4 + 12 * n
    offset = 128 + table_size
    entries, blobs = b"", b""
    shared: dict[bytes, int] = {}
    for sig, data in tags.items():
        raw_len = len(data)
        data = _pad4(data)
        if data in shared:
            off = shared[data]
        else:
            off = offset + len(blobs)
            shared[data] = off
            blobs += data
        entries += sig + struct.pack(">II", off, raw_len)
    total = 128 + table_size + len(blobs)
    header = bytearray(128)
    header[0:4] = struct.pack(">I", total)
    header[4:8] = b"lcms"
    header[8:12] = bytes([2, 0x40, 0, 0])
    header[12:16] = b"mntr"
    header[16:20] = b"RGB "
    header[20:24] = b"XYZ "
    header[24:36] = struct.pack(">HHHHHH", 2026, 1, 1, 0, 0, 0)
    header[36:40] = b"acsp"
    header[40:44] = b"APPL"
    header[64:68] = struct.pack(">I", 0)            # perceptual
    header[68:80] = _s15f16(D50_XYZ[0]) + _s15f16(D50_XYZ[1]) + _s15f16(D50_XYZ[2])
    header[80:84] = b"phst"
    return bytes(header) + struct.pack(">I", n) + entries + blobs


@lru_cache(maxsize=8)
def profile_bytes(name: str) -> bytes:
    return build_profile(name)


def pil_profile(name: str):
    """A Pillow ``ImageCmsProfile`` for ``name`` (for soft-proof / conversions)."""
    import io

    from PIL import ImageCms

    return ImageCms.ImageCmsProfile(io.BytesIO(profile_bytes(canonical(name))))


def png_iccp_chunk(profile: bytes, name: str = "ICC") -> bytes:
    data = name.encode("latin1") + b"\x00\x00" + zlib.compress(profile, 9)
    chunk = b"iCCP" + data
    return struct.pack(">I", len(data)) + chunk + struct.pack(">I", zlib.crc32(chunk) & 0xFFFFFFFF)


def embed_png_icc(png_bytes: bytes, profile: bytes) -> bytes:
    """Insert an iCCP chunk right after IHDR of an encoded PNG (replaces nothing; PNG from cv2 has none)."""
    sig, rest = png_bytes[:8], png_bytes[8:]
    ihdr_len = struct.unpack(">I", rest[:4])[0]
    end = 4 + 4 + ihdr_len + 4
    return sig + rest[:end] + png_iccp_chunk(profile) + rest[end:]
